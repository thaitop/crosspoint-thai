#!/usr/bin/env python3
"""Embed ICU's Thai word list (thaidict.txt) as a constexpr header for ThaiWordBreak.

Source: https://github.com/unicode-org/icu/blob/main/icu4c/source/data/brkitr/dictionaries/thaidict.txt
(Unicode License V3).

Words are stored in TIS-620 (one byte per Thai letter), sorted bytewise and
NUL-terminated, with the offset of every SAMPLE_STRIDE-th word indexed for
binary search.
"""

from __future__ import annotations

import argparse
import pathlib

SAMPLE_STRIDE = 16


def to_tis620(word: str) -> bytes:
    return bytes(ord(c) - 0x0E00 + 0xA0 for c in word)


def load_words(path: pathlib.Path) -> list[bytes]:
    words = set()
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        word = line.strip()
        # Skip comments and the few entries with non-Thai characters (abbreviations with '.').
        if not word or word.startswith("#") or not all(0x0E01 <= ord(c) <= 0x0E5B for c in word):
            continue
        words.add(to_tis620(word))
    return sorted(words)


def format_bytes(blob: bytes, per_line: int = 16) -> str:
    return "\n".join(
        "    " + ", ".join(f"0x{b:02X}" for b in blob[i : i + per_line]) + ","
        for i in range(0, len(blob), per_line)
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, type=pathlib.Path)
    parser.add_argument("--output", required=True, type=pathlib.Path)
    args = parser.parse_args()

    words = load_words(args.input)
    blob = bytearray()
    samples = []
    for i, word in enumerate(words):
        if i % SAMPLE_STRIDE == 0:
            samples.append(len(blob))
        blob += word + b"\0"

    index = ",\n".join(
        "    " + ", ".join(str(s) for s in samples[i : i + 12]) for i in range(0, len(samples), 12)
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        f"""#pragma once

// Generated by scripts/generate_thai_dictionary.py from ICU thaidict.txt (Unicode License V3).
// Do not edit by hand.

#include <cstddef>
#include <cstdint>

namespace thai_dict {{

constexpr size_t kWordCount = {len(words)};
constexpr size_t kSampleStride = {SAMPLE_STRIDE};
constexpr size_t kMaxWordLength = {max(len(w) for w in words)};

// Sorted TIS-620 words, each NUL-terminated.
constexpr uint8_t kWords[] = {{
{format_bytes(bytes(blob))}
}};

// Byte offset in kWords of every kSampleStride-th word.
constexpr uint32_t kSampleOffsets[] = {{
{index}
}};

}}  // namespace thai_dict
""",
        encoding="utf-8",
    )
    print(f"{len(words)} words, {len(blob)} bytes, {len(samples)} samples -> {args.output}")


if __name__ == "__main__":
    main()
