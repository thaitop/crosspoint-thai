#!/usr/bin/env python3
"""Generate src/util/ThaiLunarTable.h: Thai lunar year starts and year types.

Year types come from the Thai lunar calendar B.E. 2300-2700 tables, as listed in
python-holidays (MIT), holidays/calendars/thai.py (ATHIKAWAN_YEARS_GREGORIAN and
ATHIKAMAT_YEARS_GREGORIAN). A lunar year is labelled by the Gregorian year it
mostly falls in; it starts in November or December of the year before.

Official announcements win: put any published year that differs in
OFFICIAL_OVERRIDES. Years from FIRST_UNCHECKED_LABEL on have not been checked
against an official calendar.

Usage: python3 scripts/generate_thai_lunar_table.py > src/util/ThaiLunarTable.h
"""

from __future__ import annotations

from datetime import date, timedelta
from typing import NamedTuple

NORMAL, EXTRA_DAY, EXTRA_MONTH = 0, 1, 2
LENGTHS = {NORMAL: 354, EXTRA_DAY: 355, EXTRA_MONTH: 384}

FIRST_LABEL = 2025
LAST_LABEL = 2048  # its year starts in late 2047, so 2047-12-31 is covered
ANCHOR_START = date(2024, 12, 1)  # ขึ้น 1 ค่ำ เดือน 1 of lunar year 2025

EXTRA_DAY_YEARS = {2025, 2032, 2035, 2041, 2046}
EXTRA_MONTH_YEARS = {2026, 2029, 2031, 2034, 2037, 2040, 2043, 2045, 2048}

# label -> year type, for announced years that differ from the table above.
OFFICIAL_OVERRIDES: dict[int, int] = {}
# Official holiday dates are checked through lunar year 2026 (B.E. 2569).
FIRST_UNCHECKED_LABEL = 2027


class Year(NamedTuple):
    label: int
    start: date
    type: int


def year_type(label: int) -> int:
    if label in OFFICIAL_OVERRIDES:
        return OFFICIAL_OVERRIDES[label]
    if label in EXTRA_MONTH_YEARS:
        return EXTRA_MONTH
    if label in EXTRA_DAY_YEARS:
        return EXTRA_DAY
    return NORMAL


def years() -> list[Year]:
    out = []
    start = ANCHOR_START
    for label in range(FIRST_LABEL, LAST_LABEL + 1):
        t = year_type(label)
        out.append(Year(label, start, t))
        start += timedelta(LENGTHS[t])
    return out


def render(table: list[Year]) -> str:
    epoch = date(1970, 1, 1)
    names = {NORMAL: "NORMAL", EXTRA_DAY: "EXTRA_DAY", EXTRA_MONTH: "EXTRA_MONTH"}
    unchecked = next(i for i, y in enumerate(table) if y.label >= FIRST_UNCHECKED_LABEL)
    lines = [
        "// Generated by scripts/generate_thai_lunar_table.py. Do not edit.",
        "#pragma once",
        "// clang-format off",
        "",
        "#include <cstdint>",
        "",
        "namespace thai_lunar {",
        "",
        "// NORMAL 354 days, EXTRA_DAY 355 (month 7 has 30), EXTRA_MONTH 384 (month 8 หลัง).",
        "enum YearType : uint8_t { NORMAL = 0, EXTRA_DAY = 1, EXTRA_MONTH = 2 };",
        "",
        "// month1Start: days since 1970-01-01 of ขึ้น 1 ค่ำ เดือน 1.",
        "struct Year {",
        "  int32_t month1Start;",
        "  YearType type;",
        "};",
        "",
        "constexpr Year YEARS[] = {",
    ]
    for y in table:
        lines.append(f"    {{{(y.start - epoch).days}, {names[y.type]}}},  // {y.label} starts {y.start.isoformat()}")
    lines += [
        "};",
        "",
        "// Entries from this index on are computed, not checked against an official calendar.",
        f"constexpr int FIRST_UNCHECKED_INDEX = {unchecked};",
        "",
        "}  // namespace thai_lunar",
        "// clang-format on",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    print(render(years()), end="")
